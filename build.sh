#!/bin/sh
# Builds theme.css from src/theme.css, embedding the fonts in fonts/ as
# base64 (Obsidian themes can't load font files that sit next to them),
# and optionally installs the theme into one or more vaults.
#
#   ./build.sh                          build only
#   ./build.sh ~/Notes ~/Obsidian/Test  build, then install into each vault
set -eu

here=$(cd "$(dirname "$0")" && pwd)
fonts="$here/fonts"

face() { # family style weight file
    printf '@font-face { font-family: "%s"; font-style: %s; font-weight: %s; font-display: swap; src: url(data:font/woff2;base64,%s) format("woff2"); }\n' \
        "$1" "$2" "$3" "$(base64 < "$fonts/$4" | tr -d '\n')"
}

{
    # Keep the leading @settings comment (Style Settings reads it) exactly as written; strip
    # every other comment and all indentation and blank lines from the rest.
    awk '
        first { print; if ($0 ~ /\*\//) first = 0; next }
        BEGIN { first = 1; inc = 0 }
        {
            out = ""; s = $0
            while (length(s) > 0) {
                if (inc) { i = index(s, "*/"); if (i == 0) { s = "" } else { s = substr(s, i + 2); inc = 0 } }
                else     { i = index(s, "/*"); if (i == 0) { out = out s; s = "" } else { out = out substr(s, 1, i - 1); s = substr(s, i + 2); inc = 1 } }
            }
            gsub(/^[ \t]+/, "", out); gsub(/[ \t]+$/, "", out)
            if (out != "") print out
        }' "$here/src/theme.css"
    printf '\n/* ---------- Embedded fonts (generated by build.sh, latin subset, SIL OFL 1.1: see fonts/OFL.txt) ---------- */\n'
    face "Outfit"            normal "300 700" outfit-normal-300-700-latin.woff2
    face "Newsreader"        italic 400       newsreader-italic-400-latin.woff2
    face "Manrope"           normal "300 700" manrope-normal-300-700-latin.woff2
    face "Instrument Serif"  italic 400       instrument-serif-italic-400-latin.woff2
    face "iA Writer Duo"     normal 400       iAWriterDuoS-Regular.woff2
} > "$here/theme.css"
echo "Built $here/theme.css ($(du -h "$here/theme.css" | cut -f1 | tr -d ' '))"

for vault in "$@"; do
    target="$vault/.obsidian/themes/Suliworld"
    mkdir -p "$target"
    cp "$here/theme.css" "$here/manifest.json" "$target/"
    echo "Installed into $target"
done
